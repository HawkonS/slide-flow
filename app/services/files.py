def _content_disposition(filename: str) -> str:
    quoted = quote(filename)
    return f"attachment; filename*=UTF-8''{quoted}"


def _preview_thumb_path(source_path: Path, version_id: int) -> Path:
    thumbs_dir = settings.thumbs_dir
    thumbs_dir.mkdir(parents=True, exist_ok=True)
    mtime = source_path.stat().st_mtime_ns
    return thumbs_dir / f"preview_v{version_id}_{mtime}_{settings.image_thumb_width}x{settings.image_thumb_height}_q{settings.image_thumb_quality}.jpg"


def _preview_thumb_bytes(source_path: Path) -> bytes:
    """Render a transient JPEG thumbnail without persisting a second asset."""
    thumb_w = settings.image_thumb_width
    thumb_h = settings.image_thumb_height
    with Image.open(source_path) as image:
        image.thumbnail((thumb_w, thumb_h), Image.Resampling.LANCZOS)
        canvas = Image.new("RGB", (thumb_w, thumb_h), (248, 250, 252))
        if image.mode != "RGBA":
            image = image.convert("RGBA")
        left = (thumb_w - image.width) // 2
        top = (thumb_h - image.height) // 2
        canvas.paste(image, (left, top), image)
        buffer = io.BytesIO()
        canvas.save(buffer, format="JPEG", quality=settings.image_thumb_quality, optimize=True, progressive=True)
        return buffer.getvalue()


def _ensure_preview_thumb(source_path: Path, version_id: int) -> Path:
    target = _preview_thumb_path(source_path, version_id)
    if target.exists():
        return target
    # Write to a sibling temporary file and publish it atomically.  A failed
    # PIL encode (or a worker interruption) must never leave a truncated JPEG
    # at the cache path that subsequent requests would mistake for a valid
    # thumbnail.
    temp_target = target.with_name(f".{target.name}.{uuid.uuid4().hex}.tmp")
    try:
        temp_target.write_bytes(_preview_thumb_bytes(source_path))
        os.replace(temp_target, target)
        return target
    finally:
        temp_target.unlink(missing_ok=True)


